"""Все единицы измерения объёма памяти"""

from enum import Enum
from typing import Dict

class Unit(Enum):
    """
    Единицы измерения памяти
    
    Атрибуты:
        B: байт
        KB: килобайт (1000 байт)
        MB: мегабайт (1000 KB)
        GB: гигабайт (1000 MB)
        TB: терабайт (1000 GB)
        PB: петабайт (1000 TB)
        EB: эксабайт (1000 PB)
        ZB: зеттабайт (1000 EB)
        YB: йоттабайт (1000 ZB)
        
        KiB: кибибайт (1024 байта)
        MiB: мебибайт (1024 KiB)
        GiB: гибибайт (1024 MiB)
        TiB: тебибайт (1024 GiB)
        PiB: пебибайт (1024 TiB)
        EiB: эксбибайт (1024 PiB)
        ZiB: зебибайт (1024 EiB)
        YiB: йобибайт (1024 ZiB)
        
        IPY: айпибайт (2^90 байт)
        HPY: эйчпибайт (1000 IPY)
        GPY: джипибайт (1000 HPY)
        JPY: джейпибайт (1000 GPY)
    """
    
    # ========== Десятичные единицы (основание 1000) ==========
    B = "B"          # байт
    KB = "KB"        # килобайт (1000 B)
    MB = "MB"        # мегабайт (1000 KB)
    GB = "GB"        # гигабайт (1000 MB)
    TB = "TB"        # терабайт (1000 GB)
    PB = "PB"        # петабайт (1000 TB)
    EB = "EB"        # эксабайт (1000 PB)
    ZB = "ZB"        # зеттабайт (1000 EB)
    YB = "YB"        # йоттабайт (1000 ZB)
    
    # ========== Двоичные единицы (основание 1024) ==========
    KIB = "KiB"      # кибибайт (1024 B)
    MIB = "MiB"      # мебибайт (1024 KiB)
    GIB = "GiB"      # гибибайт (1024 MiB)
    TIB = "TiB"      # тебибайт (1024 GiB)
    PIB = "PiB"      # пебибайт (1024 TiB)
    EIB = "EiB"      # эксбибайт (1024 PiB)
    ZIB = "ZiB"      # зебибайт (1024 EiB)
    YIB = "YiB"      # йобибайт (1024 ZiB)
    
    # ========== Шуточные единицы (для гиков) ==========
    IPY = "IPY"      # айпибайт (2^90 байт)
    HPY = "HPY"      # эйчпибайт (1000 IPY)
    GPY = "GPY"      # джипибайт (1000 HPY)
    JPY = "JPY"      # джейпибайт (1000 GPY)


# ========== Коэффициенты перевода в БАЙТЫ ==========
TO_BYTES: Dict[Unit, float] = {
    # Десятичные
    Unit.B:   1,
    Unit.KB:  1000,
    Unit.MB:  1000**2,
    Unit.GB:  1000**3,
    Unit.TB:  1000**4,
    Unit.PB:  1000**5,
    Unit.EB:  1000**6,
    Unit.ZB:  1000**7,
    Unit.YB:  1000**8,
    
    # Двоичные
    Unit.KIB: 1024,
    Unit.MIB: 1024**2,
    Unit.GIB: 1024**3,
    Unit.TIB: 1024**4,
    Unit.PIB: 1024**5,
    Unit.EIB: 1024**6,
    Unit.ZIB: 1024**7,
    Unit.YIB: 1024**8,
    
    # Шуточные
    Unit.IPY: 2**90,
    Unit.HPY: 1000 * (2**90),
    Unit.GPY: 1000**2 * (2**90),
    Unit.JPY: 1000**3 * (2**90),
}

